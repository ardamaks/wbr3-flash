// bootswap: replace the stock Tuya partition table (0x0) + bootloader (0x4000) with the
// OBK 1.18.313 ones, in place, from running OBK. RTL87X0C (WBR3) only.
//   bootswap check                 read-only: report state, change nothing
//   bootswap go I_ACCEPT_BRICK     do it (refuses unless the state is exactly known)
// Brick window = the erase/program of 8 sectors. A failed verify retries forever instead of
// rebooting: a running OBK can still fix flash, a rebooted one can't.
#include "../../new_common.h"
#include "../../logging/logging.h"
#include "../../cmnds/cmd_public.h"
#include "../hal_generic.h"
#include "flash_api.h"
#include "device_lock.h"
#include "bootswap_blobs.h"   // generated by build.sh: pt_new, bl_new, pt_stock, bl_stock (+ _len)

extern flash_t flash;
extern uint32_t sys_update_ota_get_curr_fw_idx(void);
extern void get_fw_info(uint32_t* targetFWaddr, uint32_t* currentFWaddr, uint32_t* fw1_sn, uint32_t* fw2_sn);

#define PT_ADDR  0x0
#define BL_ADDR  0x4000
#define BL_END   0x10000   // the new bootloader blob is shorter; the rest must stay 0xFF
#define SECT     0x1000
#define FW1_ADDR 0x10000
#define FW2_ADDR 0xF0000

#define LOG(...) ADDLOG_INFO(LOG_FEATURE_CMD, __VA_ARGS__)

static uint8_t *g_buf;   // one sector; writes must come from RAM, not from XIP flash

static int flash_eq(uint32_t addr, const uint8_t *want, uint32_t len) {
	for (uint32_t o = 0; o < len; o += SECT) {
		uint32_t n = len - o < SECT ? len - o : SECT;
		device_mutex_lock(RT_DEV_LOCK_FLASH);
		flash_stream_read(&flash, addr + o, n, g_buf);
		device_mutex_unlock(RT_DEV_LOCK_FLASH);
		if (want ? memcmp(g_buf, want + o, n) : 0) return 0;
		if (!want) for (uint32_t i = 0; i < n; i++) if (g_buf[i] != 0xFF) return 0;
	}
	return 1;
}

static void write_sector_verified(uint32_t addr, const uint8_t *src, uint32_t n) {
	uint8_t *rd = g_buf + SECT;
	for (int tries = 1;; tries++) {
		memset(g_buf, 0xFF, SECT);
		memcpy(g_buf, src, n);
		device_mutex_lock(RT_DEV_LOCK_FLASH);
		flash_erase_sector(&flash, addr);
		flash_burst_write(&flash, addr, SECT, g_buf);
		flash_stream_read(&flash, addr, SECT, rd);
		device_mutex_unlock(RT_DEV_LOCK_FLASH);
		if (!memcmp(g_buf, rd, SECT)) return;
		ADDLOG_ERROR(LOG_FEATURE_CMD, "bootswap: verify fail @0x%x try %d, retrying", addr, tries);
		rtos_delay_milliseconds(100);
	}
}

// 0 = stock (swap possible), 1 = already OBK, -1 = unknown/unsafe
static int boot_state(void) {
	int pt_s = flash_eq(PT_ADDR, pt_stock, pt_stock_len), bl_s = flash_eq(BL_ADDR, bl_stock, bl_stock_len);
	int pt_n = flash_eq(PT_ADDR, pt_new, pt_new_len),     bl_n = flash_eq(BL_ADDR, bl_new, bl_new_len);
	int tail_ff = flash_eq(BL_ADDR + bl_new_len, NULL, BL_END - BL_ADDR - bl_new_len);
	LOG("bootswap: ptable stock=%d obk=%d | boot stock=%d obk=%d | 0x%x..0x%x erased=%d",
		pt_s, pt_n, bl_s, bl_n, BL_ADDR + bl_new_len, BL_END, tail_ff);
	if (pt_n && bl_n && tail_ff) return 1;
	if (pt_s && bl_s && tail_ff) return 0;
	return -1;
}

// The OBK bootloader picks the slot by validity + serial number and ignores Tuya's bit counter
// at sysdata 0x1004, so the running slot must be the only valid one before the swap.
static int slots_ok(uint32_t *other) {
	uint32_t target, current, sn1, sn2, idx = sys_update_ota_get_curr_fw_idx(), w = 0;
	get_fw_info(&target, &current, &sn1, &sn2);
	*other = idx == 1 ? FW2_ADDR : FW1_ADDR;
	device_mutex_lock(RT_DEV_LOCK_FLASH);
	flash_read_word(&flash, *other, &w);
	device_mutex_unlock(RT_DEV_LOCK_FLASH);
	LOG("bootswap: running fw%u (current 0x%x, target 0x%x, sn1 %u, sn2 %u), other slot 0x%x first word 0x%08x",
		idx, current, target, sn1, sn2, *other, w);
	return (idx == 1 || idx == 2) && current == (idx == 1 ? FW1_ADDR : FW2_ADDR) && target == *other;
}

static commandResult_t CMD_BootSwap(const void *ctx, const char *cmd, const char *args, int flags) {
	Tokenizer_TokenizeString(args, 0);
	const char *mode = Tokenizer_GetArg(0), *confirm = Tokenizer_GetArg(1);
	if (!mode) mode = "";
	int go = !strcmp(mode, "go") && confirm && !strcmp(confirm, "I_ACCEPT_BRICK");
	if (!go && strcmp(mode, "check")) {
		LOG("bootswap: usage: bootswap check | bootswap go I_ACCEPT_BRICK");
		return CMD_RES_BAD_ARGUMENT;
	}
	g_buf = malloc(2 * SECT);
	if (!g_buf) return CMD_RES_ERROR;
	commandResult_t res = CMD_RES_ERROR;
	uint32_t other;
	int st = boot_state(), slots = slots_ok(&other);

	if (st == 1) { LOG("bootswap: already OBK bootloader + ptable, nothing to do"); res = CMD_RES_OK; goto out; }
	if (st != 0 || !slots) { LOG("bootswap: REFUSING, flash is not in the known stock state"); goto out; }
	if (!go) { LOG("bootswap: check OK, 'bootswap go I_ACCEPT_BRICK' would swap"); res = CMD_RES_OK; goto out; }

	// 1. invalidate the other slot (same as OBK's OTA does to the old slot: first word -> 0)
	device_mutex_lock(RT_DEV_LOCK_FLASH);
	flash_write_word(&flash, other, 0);
	device_mutex_unlock(RT_DEV_LOCK_FLASH);
	// 2. bootloader first: new boot + old ptable share the same boot/fw hash keys
	for (uint32_t o = 0; o < bl_new_len; o += SECT)
		write_sector_verified(BL_ADDR + o, bl_new + o, bl_new_len - o < SECT ? bl_new_len - o : SECT);
	// 3. partition table last, one sector
	write_sector_verified(PT_ADDR, pt_new, pt_new_len);
	// 4. full re-check before we let it reboot
	if (boot_state() != 1) { ADDLOG_ERROR(LOG_FEATURE_CMD, "bootswap: FINAL CHECK FAILED, DO NOT POWER OFF, run 'bootswap check'"); goto out; }
	LOG("bootswap: done, rebooting into the OBK bootloader");
	res = CMD_RES_OK;
	HAL_RebootModule();
out:
	free(g_buf);
	return res;
}

void BootSwap_Init(void) {
	//cmddetail:{"name":"bootswap","args":"check | go I_ACCEPT_BRICK",
	//cmddetail:"descr":"RTL87X0C: replace Tuya ptable+bootloader with OBK's (wbr3-flash project)",
	//cmddetail:"fn":"CMD_BootSwap","file":"hal/realtek/bootswap.c","requires":"",
	//cmddetail:"examples":""}
	CMD_RegisterCommand("bootswap", CMD_BootSwap, NULL);
}
